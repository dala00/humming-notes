export const MESSAGES = { en, ja };

// First candidate ("ja-JP", "en_US.UTF-8", ...) whose language we have; English otherwise.
export function pickLang(...candidates) {
  for (const c of candidates) {
    const code = String(c || '').toLowerCase().split(/[-_.]/)[0];
    if (MESSAGES[code]) return code;
  }
  return 'en';
}

// t(key, {name: value}) fills {name} placeholders. A key missing from `lang` falls back to English.
export function translator(lang) {
  const dict = MESSAGES[lang] || en;
  const t = (key, params = {}) => String(dict[key] ?? en[key] ?? key).replace(/\{(\w+)\}/g, (m, k) => (k in params ? params[k] : m));
  t.lang = MESSAGES[lang] ? lang : 'en';
  t.has = (key) => key in dict || key in en;
  return t;
}
